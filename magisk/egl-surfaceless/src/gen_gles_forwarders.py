"""Generate gles_forwarders.c: one forwarding stub per function exported by WSA's
libGLESv2_emulation.so, except the ones gles_wrapper.c implements itself.

usage: python gen_gles_forwarders.py <libGLESv2_emulation.so> <out.c>
WSA is no longer updated, so the generated file is committed; rerun only if the
driver changes.
"""
import sys
from elftools.elf.elffile import ELFFile

OVERRIDDEN = {'_Z14getProcAddressPKc', 'glBindFramebuffer', 'glDrawBuffers', 'glReadBuffer',
              'glFramebufferTexture2D', 'glFramebufferRenderbuffer', 'glClear', 'glColorMask',
              'glBlitFramebuffer', 'glCopyTexSubImage2D', 'glInvalidateFramebuffer', 'glBindTexture',
              'glGenerateMipmap', 'glDrawElements', 'glDrawRangeElements', 'glDrawElementsInstanced',
              'glDrawArrays', 'glDrawArraysInstanced', 'glBufferData', 'glBufferSubData',
              'glDeleteBuffers', 'glMapBufferRange', 'glGenVertexArrays', 'glDeleteVertexArrays',
              'glBindVertexArray', 'glIsVertexArray', 'glVertexAttribPointer', 'glVertexAttribIPointer',
              'glEnableVertexAttribArray', 'glDisableVertexAttribArray', 'glVertexAttribDivisor',
              'glBindBuffer', 'glGetIntegerv'}

lib, out = sys.argv[1:]
f = ELFFile(open(lib, 'rb'))
names = sorted({s.name for s in f.get_section_by_name('.dynsym').iter_symbols()
                if s['st_shndx'] != 'SHN_UNDEF' and s['st_info']['type'] == 'STT_FUNC'
                and s['st_info']['bind'] in ('STB_GLOBAL', 'STB_WEAK')} - OVERRIDDEN)

with open(out, 'w', newline='\n') as o:
    o.write('/* Generated by gen_gles_forwarders.py from WSA 2407.40000 libGLESv2_emulation.so. */\n')
    o.write('#define N_FWD %d\n' % len(names))
    o.write('__attribute__((visibility("hidden"))) void *g_fwd[N_FWD];\n')
    o.write('__attribute__((visibility("hidden"))) const char *const g_fwd_names[N_FWD] = {\n')
    for n in names:
        o.write('    "%s",\n' % n)
    o.write('};\n\n')
    o.write('/* Each stub jumps to the real function: x16 = g_fwd[i]; br x16 (arguments untouched). */\n')
    o.write('__asm__(".text\\n"\n')
    for i, n in enumerate(names):
        o.write('    ".globl %s\\n.type %s,%%function\\n%s:\\n'
                '  adrp x16, g_fwd+%d\\n  ldr x16, [x16, #:lo12:g_fwd+%d]\\n  br x16\\n"\n'
                % (n, n, n, 8 * i, 8 * i))
    o.write(');\n')
print('%d forwarders -> %s' % (len(names), out))
